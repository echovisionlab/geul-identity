func TestManageRulesGroupEveryExactRPCByRole(t *testing.T) {
	routes := repositoryRouteConfig(t)
	rules, err := generateRules(routes)
	if err != nil {
		t.Fatalf("generateRules() error = %v", err)
	}
	roles, err := collectManageAuthorizationRoles()
	if err != nil {
		t.Fatalf("collectManageAuthorizationRoles() error = %v", err)
	}

	roleOrder := []policyv1.AuthorizationRole{
		policyv1.AuthorizationRole_ADMIN,
		policyv1.AuthorizationRole_AUTHOR,
		policyv1.AuthorizationRole_USER,
	}
	if got := bytes.Count(rules, []byte("- id: manage-")); got != len(roleOrder) {
		t.Fatalf("generated Manage rules = %d, want one for each of %d roles", got, len(roleOrder))
	}

	matchers := make(map[policyv1.AuthorizationRole]*regexp.Regexp, len(roleOrder))
	for _, role := range roleOrder {
		block := ruleBlock(t, rules, "manage-"+roleID(role))
		if bytes.Contains(block, []byte(`api\.manage\.v1\..*`)) {
			t.Fatalf("%s Manage rule contains a package wildcard:\n%s", role, block)
		}
		matchers[role] = ruleURLRegexp(t, block)
	}

	for expectedRole, services := range roles {
		for service, methods := range services {
			for _, method := range methods {
				for _, origin := range []string{routes.Origins.API, routes.Origins.APIInternal} {
					requestURL := fmt.Sprintf("%s/api/rpc/api.manage.v1.%s/%s", origin, service, method)
					var matchedRoles []policyv1.AuthorizationRole
					for _, candidateRole := range roleOrder {
						if matchers[candidateRole].MatchString(requestURL) {
							matchedRoles = append(matchedRoles, candidateRole)
						}
					}
					if len(matchedRoles) != 1 || matchedRoles[0] != expectedRole {
						t.Errorf("%s matched roles %v, want exactly %s", requestURL, matchedRoles, expectedRole)
					}
				}
			}
		}
	}

	unknownURL := routes.Origins.API + "/api/rpc/api.manage.v1.UnknownService/UnknownProcedure"
	for role, matcher := range matchers {
		if matcher.MatchString(unknownURL) {
			t.Errorf("unknown Manage procedure matched %s", role)
		}
	}
}

