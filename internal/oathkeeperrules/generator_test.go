type gatewayTemplateSession struct {
	Subject string
	Extra   map[string]any
}

func executeGatewayTemplate(t *testing.T, source string, session gatewayTemplateSession) (string, error) {
	t.Helper()
	tmpl, err := template.New("gateway").
		Option("missingkey=zero").
		Funcs(template.FuncMap{
			"print": func(value any) string {
				if value == nil {
					return ""
				}
				return fmt.Sprintf("%v", value)
			},
		}).
		Funcs(sprig.TxtFuncMap()).
		Parse(source)
	if err != nil {
		return "", err
	}
	var output bytes.Buffer
	err = tmpl.Execute(&output, session)
	return output.String(), err
}

func oathkeeperHeaderTemplates(t *testing.T) map[string]string {
	t.Helper()
	root := mustRepoRoot(t)
	raw, err := os.ReadFile(filepath.Join(root, "config/oathkeeper/oathkeeper.yml"))
	if err != nil {
		t.Fatalf("read Oathkeeper config: %v", err)
	}
	var config map[string]any
	if err := yaml.Unmarshal(raw, &config); err != nil {
		t.Fatalf("decode Oathkeeper config: %v", err)
	}
	mutators := config["mutators"].(map[string]any)
	header := mutators["header"].(map[string]any)
	headerConfig := header["config"].(map[string]any)
	rawHeaders := headerConfig["headers"].(map[string]any)
	headers := make(map[string]string, len(rawHeaders))
	for name, value := range rawHeaders {
		headers[name] = value.(string)
	}
	return headers
}

