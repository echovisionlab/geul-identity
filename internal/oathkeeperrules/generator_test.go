func TestGeneratedRulesRestrictHTTPMethods(t *testing.T) {
	rules, err := generateRules(repositoryRouteConfig(t))
	if err != nil {
		t.Fatalf("generateRules() error = %v", err)
	}

	manageStart := bytes.Index(rules, []byte("# Manage API -"))
	mcpStart := bytes.Index(rules, []byte("# Remote MCP -"))
	if manageStart < 0 || mcpStart <= manageStart {
		t.Fatalf("manage or MCP section missing")
	}
	manageRules := rules[manageStart:mcpStart]
	for _, forbidden := range [][]byte{
		[]byte("      - GET\n"),
		[]byte("      - PUT\n"),
		[]byte("      - PATCH\n"),
		[]byte("      - DELETE\n"),
	} {
		if bytes.Contains(manageRules, forbidden) {
			t.Fatalf("manage rules contain non-POST method %q", forbidden)
		}
	}

	internalRule := ruleBlock(t, rules, "block-internal-api")
	for _, method := range []string{"GET", "HEAD", "POST", "PUT", "PATCH", "DELETE", "OPTIONS"} {
		if !bytes.Contains(internalRule, []byte("      - "+method+"\n")) {
			t.Errorf("internal API deny rule is missing %s", method)
		}
	}
	openRule := ruleBlock(t, rules, "open-api")
	if !bytes.Contains(openRule, []byte("      - POST\n")) || bytes.Contains(openRule, []byte("      - GET\n")) {
		t.Errorf("open API rule must allow POST only:\n%s", openRule)
	}
}

