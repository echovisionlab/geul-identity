func ruleBlock(t *testing.T, rules []byte, id string) []byte {
	t.Helper()
	start := bytes.Index(rules, []byte("- id: "+id+"\n"))
	if start < 0 {
		t.Fatalf("rule %s not found", id)
	}
	rest := rules[start:]
	if next := bytes.Index(rest[1:], []byte("\n- id: ")); next >= 0 {
		return rest[:next+1]
	}
	return rest
}

func ruleURLRegexp(t *testing.T, block []byte) *regexp.Regexp {
	t.Helper()
	match := regexp.MustCompile(`(?m)^    url: '<([^']+)>'$`).FindSubmatch(block)
	if len(match) != 2 {
		t.Fatalf("rule URL matcher missing:\n%s", block)
	}
	compiled, err := regexp.Compile("^(?:" + string(match[1]) + ")$")
	if err != nil {
		t.Fatalf("compile rule URL matcher %q: %v", match[1], err)
	}
	return compiled
}

func manageRegistryWithMethods(t *testing.T, policy *policyv1.AccessPolicy, methodNames ...string) *protoregistry.Files {
	t.Helper()
	methods := make([]*descriptorpb.MethodDescriptorProto, 0, len(methodNames))
	for _, methodName := range methodNames {
		options := &descriptorpb.MethodOptions{}
		if policy != nil {
			proto.SetExtension(options, policyv1.E_Access, policy)
		}
		methods = append(methods, &descriptorpb.MethodDescriptorProto{
			Name:       proto.String(methodName),
			InputType:  proto.String(".api.manage.v1.FixtureRequest"),
			OutputType: proto.String(".api.manage.v1.FixtureResponse"),
			Options:    options,
		})
	}
	file, err := protodesc.NewFile(&descriptorpb.FileDescriptorProto{
		Name:       proto.String("fixture/manage.proto"),
		Package:    proto.String("api.manage.v1"),
		Syntax:     proto.String("proto3"),
		Dependency: []string{policyv1.File_api_policy_v1_access_proto.Path()},
		MessageType: []*descriptorpb.DescriptorProto{
			{Name: proto.String("FixtureRequest")},
			{Name: proto.String("FixtureResponse")},
		},
		Service: []*descriptorpb.ServiceDescriptorProto{{
			Name:   proto.String("FixtureService"),
			Method: methods,
		}},
	}, protoregistry.GlobalFiles)
	if err != nil {
		t.Fatalf("build fixture descriptor: %v", err)
	}
	registry := new(protoregistry.Files)
	if err := registry.RegisterFile(file); err != nil {
		t.Fatalf("register fixture descriptor: %v", err)
	}
	return registry
}
