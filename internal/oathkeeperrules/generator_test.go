func TestAuthRulesAreAnonymousNoopAndCannotMatchProductAPIs(t *testing.T) {
	rules, err := generateRules(repositoryRouteConfig(t))
	if err != nil {
		t.Fatalf("generateRules() error = %v", err)
	}

	for _, id := range []string{
		"auth-preflight",
		"auth-login",
		"auth-login-flows",
		"auth-self-service-read",
		"auth-self-service-submit",
		"auth-sessions",
		"auth-schemas",
		"auth-health",
		"auth-webauthn-runtime",
	} {
		block := ruleBlock(t, rules, id)
		for _, want := range [][]byte{
			[]byte("    - handler: anonymous\n"),
			[]byte("    - handler: noop\n"),
			[]byte("    url: 'http://api.example.invalid:8000'\n"),
		} {
			if !bytes.Contains(block, want) {
				t.Errorf("auth rule %s is missing %q:\n%s", id, want, block)
			}
		}
		for _, forbidden := range [][]byte{
			[]byte("handler: cookie_session"),
			[]byte("handler: bearer_token"),
			[]byte("handler: header"),
			[]byte("api\\.manage"),
			[]byte("api\\.open"),
			[]byte("api\\.intra"),
			[]byte("/upload/"),
			[]byte("/hooks/"),
		} {
			if bytes.Contains(block, forbidden) {
				t.Errorf("auth rule %s contains forbidden authority or product route %q:\n%s", id, forbidden, block)
			}
		}
	}

	apiHealth := ruleBlock(t, rules, "api-health")
	if !bytes.Contains(apiHealth, []byte(`url: '<https://site\.example\.invalid/health>'`)) {
		t.Errorf("API health rule is not exact:\n%s", apiHealth)
	}
	if !bytes.Contains(apiHealth, []byte("    - handler: header\n")) {
		t.Errorf("API health does not scrub caller credentials:\n%s", apiHealth)
	}
	for _, forbidden := range [][]byte{[]byte("/health(?:"), []byte("/health/.*")} {
		if bytes.Contains(apiHealth, forbidden) {
			t.Errorf("API health rule contains path-family alias %q:\n%s", forbidden, apiHealth)
		}
	}

	for id, want := range map[string]string{
		"auth-login":               `url: '<https://site\.example\.invalid/api/auth/login>'`,
		"auth-login-flows":         `url: '<https://site\.example\.invalid/api/auth/login/flows>'`,
		"auth-self-service-read":   `url: '<https://site\.example\.invalid/api/auth/self-service/(?:(?:verification|settings)/(?:browser|flows)|logout(?:/browser)?|errors|methods/oidc/callback/[^/]+)>'`,
		"auth-self-service-submit": `url: '<https://site\.example\.invalid/api/auth/self-service/(?:verification|settings)>'`,
	} {
		block := ruleBlock(t, rules, id)
		if !bytes.Contains(block, []byte(want)) {
			t.Errorf("auth rule %s does not use its exact hard-cut matcher:\n%s", id, block)
		}
		if bytes.Contains(block, []byte("/?")) {
			t.Errorf("auth rule %s retains a trailing-slash alias:\n%s", id, block)
		}
	}
	for _, forbidden := range [][]byte{
		[]byte(`url: '<https://site\.example\.invalid/auth`),
		[]byte(`url: '<https://site\.example\.invalid/verification`),
	} {
		if bytes.Contains(rules, forbidden) {
			t.Errorf("generated rules retain removed user-facing route alias %q", forbidden)
		}
	}

	preflight := ruleBlock(t, rules, "auth-preflight")
	wantMatcher := `url: '<https://site\.example\.invalid/api/auth(?:/login(?:/flows)?|/self-service/(?:(?:verification|settings)(?:/(?:browser|flows))?|logout(?:/browser)?|errors|methods/oidc/callback/[^/]+)|/sessions/.*|/schemas/.*|/health/.*|/\.well-known/ory/webauthn\.js)>'`
	if !bytes.Contains(preflight, []byte(wantMatcher)) {
		t.Errorf("auth preflight is not bounded to the non-preflight route families:\n%s", preflight)
	}
	for _, forbidden := range []string{"/self-service/.*", "recovery", "/api\\.", "/upload/", "/hooks/"} {
		if bytes.Contains(preflight, []byte(forbidden)) {
			t.Errorf("auth preflight contains broader forbidden matcher %q:\n%s", forbidden, preflight)
		}
	}
	for _, blockID := range []string{"auth-preflight", "auth-self-service-read", "auth-self-service-submit"} {
		matcher := ruleURLRegexp(t, ruleBlock(t, rules, blockID))
		for _, rawPath := range []string{
			"/self-service/login/browser",
			"/self-service/login/flows",
			"/self-service/login",
			"/self-service/registration/browser",
			"/self-service/registration/flows",
			"/self-service/registration",
		} {
			if matcher.MatchString("https://site.example.invalid" + rawPath) {
				t.Errorf("auth rule %s publicly exposes retired raw browser controller %q", blockID, rawPath)
			}
		}
	}
}

