import fs from "node:fs";
import path from "node:path";

const root = path.resolve(new URL("../..", import.meta.url).pathname);
const schemaPath = path.join(root, "config/spicedb/schema.generated.zed");
const localEventContractsSchemaPath = path.join(
  root,
  "..",
  "event-contracts",
  "config/spicedb/schema.generated.zed",
);
const generatedCatalogPath = path.join(
  root,
  "config/spicedb/catalog.generated.ts",
);

const schema = fs.readFileSync(schemaPath, "utf8");
const catalogFingerprintMatches = [
  ...schema.matchAll(/^\/\/ Catalog fingerprint: ([0-9a-f]{64})$/gm),
];
if (catalogFingerprintMatches.length !== 1) {
  throw new Error(
    "schema.generated.zed must contain one canonical catalog fingerprint header",
  );
}
const catalogFingerprint = catalogFingerprintMatches[0][1];
if (fs.existsSync(localEventContractsSchemaPath)) {
  const localSchema = fs.readFileSync(localEventContractsSchemaPath, "utf8");
  if (localSchema !== schema) {
    throw new Error(
      "identity SpiceDB schema.generated.zed differs from local event-contracts artifact",
    );
  }
}
const definitions = [
  ...schema.matchAll(/^definition ([a-z][a-z0-9_]*)\s*\{/gm),
].map(([, name]) => name);
const baseDefinitions = new Set(["account_identity", "role", "platform"]);
const resourceTypes = definitions.filter((name) => !baseDefinitions.has(name));
if (
  resourceTypes.length === 0 ||
  new Set(definitions).size !== definitions.length
) {
  throw new Error(
    "schema.generated.zed must contain a unique closed resource definition set",
  );
}

const capabilities = {};
for (const resourceType of resourceTypes) {
  const start = schema.indexOf(`definition ${resourceType} {`);
  const next = schema.indexOf("\ndefinition ", start + 1);
  const block = schema.slice(start, next === -1 ? undefined : next);
  const relations = [
    ...block.matchAll(/^  relation ([a-z][a-z0-9_]*)\s*:/gm),
  ].map(([, name]) => name);
  const permissions = [
    ...block.matchAll(/^  permission ([a-z][a-z0-9_]*)\s*=/gm),
  ].map(([, name]) => name);
  capabilities[resourceType] = { relations, permissions };
}

const generatedCatalog = `// Code generated by scripts/ci/generate-spicedb-schema.mjs.\n// DO NOT EDIT.\n\nexport const spiceDbResourceTypes = ${JSON.stringify(resourceTypes, null, 2)} as const;\n\nexport type SpiceDbResourceType = (typeof spiceDbResourceTypes)[number];\n\nexport const spiceDbCapabilities = ${JSON.stringify(capabilities, null, 2)} as const satisfies Record<\n  SpiceDbResourceType,\n  { readonly relations: readonly string[]; readonly permissions: readonly string[] }\n>;\n\nexport type SpiceDbRelation = (typeof spiceDbCapabilities)[SpiceDbResourceType]["relations"][number];\nexport type SpiceDbPermission = (typeof spiceDbCapabilities)[SpiceDbResourceType]["permissions"][number];\n`;
const generatedCatalogWithFingerprint = generatedCatalog.replace(
  "// DO NOT EDIT.\n\n",
  `// DO NOT EDIT.\n\nexport const spiceDbCatalogFingerprint = ${JSON.stringify(catalogFingerprint)} as const;\n\n`,
);
for (const [file, content] of [
  [generatedCatalogPath, generatedCatalogWithFingerprint],
]) {
  fs.writeFileSync(file, content);
}
